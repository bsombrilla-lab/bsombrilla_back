CREATE TABLE IF NOT EXISTS lineas_ayuda (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    numero VARCHAR(40) NOT NULL,
    descripcion VARCHAR(300) NULL,
    horario VARCHAR(120) NULL,
    categoria VARCHAR(60) NULL,
    orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_lineas_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS servicios_mapa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(140) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    ciudad VARCHAR(80) NOT NULL,
    direccion VARCHAR(200) NULL,
    telefono VARCHAR(80) NULL,
    horario VARCHAR(140) NULL,
    descripcion VARCHAR(400) NULL,
    lat DECIMAL(10, 7) NOT NULL,
    lng DECIMAL(10, 7) NOT NULL,
    web VARCHAR(300) NULL,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_servicios_nombre_ciudad UNIQUE (nombre, ciudad)
);

CREATE INDEX IF NOT EXISTS idx_servicios_categoria
    ON servicios_mapa (categoria);

CREATE INDEX IF NOT EXISTS idx_servicios_ciudad
    ON servicios_mapa (ciudad);

-- ==========================================================
-- REGISTRO DE ACCESOS Y LOGROS LABORALES
-- ==========================================================

CREATE TABLE IF NOT EXISTS accesos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_accesos_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_accesos_usuaria_fecha
    ON accesos (usuaria_id, creado_en);

CREATE TABLE IF NOT EXISTS logros_laborales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    empresa VARCHAR(120) NOT NULL,
    cargo VARCHAR(120) NULL,
    fecha DATE NOT NULL,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_logros_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_logros_fecha
    ON logros_laborales (fecha);
