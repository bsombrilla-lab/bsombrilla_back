
-- ==========================================================
-- Bajo la sombrilla - esquema de base de datos
-- PostgreSQL
-- Las fechas se almacenan en UTC.
-- ==========================================================

CREATE TABLE IF NOT EXISTS usuarias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'usuaria'
        CHECK (rol IN ('usuaria', 'profesional', 'admin')),
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_usuarias_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS areas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT uq_areas_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS testimonios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NULL,
    nombre_publico VARCHAR(80) NULL,
    texto TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'aprobado', 'rechazado')),
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_testimonios_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_testimonios_estado
    ON testimonios (estado);

CREATE TABLE IF NOT EXISTS testimonio_areas (
    testimonio_id INTEGER NOT NULL,
    area_id INTEGER NOT NULL,
    PRIMARY KEY (testimonio_id, area_id),
    CONSTRAINT fk_ta_testimonio
        FOREIGN KEY (testimonio_id) REFERENCES testimonios (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_ta_area
        FOREIGN KEY (area_id) REFERENCES areas (id)
);

CREATE TABLE IF NOT EXISTS motivos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT uq_motivos_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS solicitudes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NULL,
    contacto VARCHAR(120) NULL,
    mensaje TEXT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'nueva'
        CHECK (estado IN ('nueva', 'atendida')),
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_solicitudes_estado
    ON solicitudes (estado);

CREATE TABLE IF NOT EXISTS solicitud_motivos (
    solicitud_id INTEGER NOT NULL,
    motivo_id INTEGER NOT NULL,
    PRIMARY KEY (solicitud_id, motivo_id),
    CONSTRAINT fk_sm_solicitud
        FOREIGN KEY (solicitud_id) REFERENCES solicitudes (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_sm_motivo
        FOREIGN KEY (motivo_id) REFERENCES motivos (id)
);

-- ==========================================================
-- MÓDULO DE ACOMPAÑAMIENTO PSICOSOCIAL
-- ==========================================================

CREATE TABLE IF NOT EXISTS perfiles_profesionales (
    usuaria_id INTEGER PRIMARY KEY,
    especialidad VARCHAR(120) NOT NULL,
    descripcion TEXT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_perfil_prof_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

-- Horarios semanales: 0 = domingo, 1 = lunes, ... 6 = sábado

CREATE TABLE IF NOT EXISTS disponibilidad (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesional_id INTEGER NOT NULL,
    dia_semana SMALLINT NOT NULL
        CHECK (dia_semana BETWEEN 0 AND 6),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT fk_disponibilidad_prof
        FOREIGN KEY (profesional_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_disponibilidad_prof
    ON disponibilidad (profesional_id);

CREATE TABLE IF NOT EXISTS citas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    profesional_id INTEGER NOT NULL,
    fecha_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    duracion_min SMALLINT NOT NULL DEFAULT 50
        CHECK (duracion_min >= 0),
    modalidad VARCHAR(20) NOT NULL DEFAULT 'virtual'
        CHECK (modalidad IN ('virtual', 'presencial')),
    motivo VARCHAR(500) NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'confirmada', 'completada', 'cancelada')),
    notas TEXT NULL,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_citas_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_citas_profesional
        FOREIGN KEY (profesional_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_citas_usuaria
    ON citas (usuaria_id);

CREATE INDEX IF NOT EXISTS idx_citas_profesional
    ON citas (profesional_id);

CREATE INDEX IF NOT EXISTS idx_citas_fecha
    ON citas (fecha_hora);

CREATE INDEX IF NOT EXISTS idx_citas_estado
    ON citas (estado);

CREATE TABLE IF NOT EXISTS mensajes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    profesional_id INTEGER NOT NULL,
    remitente VARCHAR(20) NOT NULL
        CHECK (remitente IN ('usuaria', 'profesional')),
    texto TEXT NOT NULL,
    leido BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_mensajes_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_mensajes_profesional
        FOREIGN KEY (profesional_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_mensajes_conversacion
    ON mensajes (usuaria_id, profesional_id, creado_en);

CREATE INDEX IF NOT EXISTS idx_mensajes_profesional
    ON mensajes (profesional_id, leido);

CREATE TABLE IF NOT EXISTS diario_emocional (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    fecha DATE NOT NULL,
    animo SMALLINT NOT NULL CHECK (animo >= 0),
    emociones VARCHAR(200) NULL,
    nota TEXT NULL,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_diario_usuaria_fecha UNIQUE (usuaria_id, fecha),
    CONSTRAINT fk_diario_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_diario_fecha
    ON diario_emocional (fecha);

CREATE TABLE IF NOT EXISTS tests_bienestar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('ansiedad', 'autoestima')),
    puntaje SMALLINT NOT NULL CHECK (puntaje >= 0),
    nivel VARCHAR(30) NOT NULL,
    respuestas TEXT NOT NULL,
    riesgo BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_tests_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_tests_usuaria
    ON tests_bienestar (usuaria_id);

CREATE INDEX IF NOT EXISTS idx_tests_riesgo
    ON tests_bienestar (riesgo);

CREATE TABLE IF NOT EXISTS alertas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuaria_id INTEGER NOT NULL,
    profesional_id INTEGER NULL,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('test', 'diario')),
    nivel VARCHAR(20) NOT NULL DEFAULT 'alto'
        CHECK (nivel IN ('medio', 'alto')),
    descripcion VARCHAR(300) NOT NULL,
    atendida BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_alertas_usuaria
        FOREIGN KEY (usuaria_id) REFERENCES usuarias (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_alertas_profesional
        FOREIGN KEY (profesional_id) REFERENCES usuarias (id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_alertas_pendientes
    ON alertas (atendida, creado_en);

CREATE INDEX IF NOT EXISTS idx_alertas_profesional
    ON alertas (profesional_id, atendida);

-- ==========================================================
